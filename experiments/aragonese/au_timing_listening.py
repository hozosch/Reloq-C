"""Compare a native AU timing probe against the preferred pauto reference.

All examples are generated by disposable experiments. This is not a voice
module and the environment controls must be used serially in one process.
"""
from __future__ import annotations

import argparse
from array import array
import os
from pathlib import Path
import sys
import wave

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'nvda'))
from _reloq_eci_direct import DirectEciEngine,PROCESS_TAGS,SAMPLE_RATE
from castilian_sh_listening import millis

PREFIX='RELOQ_ARAGON_PROBE_'


def set_controls(**values):
    for key,value in values.items():os.environ[PREFIX+key]=str(value)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline',required=True,type=Path)
    parser.add_argument('--reference',required=True,type=Path)
    parser.add_argument('--timing',required=True,type=Path)
    parser.add_argument('--mode',required=True,type=int,choices=(2,),help='validated whole-nucleus timing mode')
    parser.add_argument('--wav',required=True,type=Path)
    args=parser.parse_args()
    german=DirectEciEngine(args.baseline.resolve(),dialect=0x40000,encoding='utf8',native_voice=True)
    old=DirectEciEngine(args.reference.resolve(),dialect=0x20000,encoding='utf8',native_voice=True)
    new=DirectEciEngine(args.timing.resolve(),dialect=0x20000,encoding='utf8',native_voice=True)
    engines=(german,old,new)
    saved={k:v for k,v in os.environ.items() if k.startswith(PREFIX)}
    samples=array('h')
    try:
        for k in saved:del os.environ[k]
        set_controls(AU_PERCENT=40,SH_PERCENT=65,TIMING_MODE=0,TIMING_SCOPE=1)
        for e in engines:e.set_parameter(SAMPLE_RATE,3);e.set_parameter(PROCESS_TAGS,1)
        def render(e,text):
            pcm=bytearray()
            if not e.speak([text],pcm.extend,lambda _index:None) or not pcm:raise RuntimeError(text)
            out=array('h');out.frombytes(pcm)
            if sys.byteorder!='little':out.byteswap()
            return out
        def add(audio):samples.extend(audio);samples.extend([0]*millis(300))
        def say(text):add(render(german,text))

        say('Aragonesisch. Vergleich des Au. Pauto bleibt die bisherige Referenz.')
        pauto=render(old,'pauto')
        add(pauto)
        for label,word in (('Erstes Wort.','auca'),('Zweites Wort.','auto'),('Im Satz.','la auca')):
            say(label+' Bisher.')
            before=render(old,word);add(before)
            durations=[]
            for number,pct in ((1,85),(2,70)):
                set_controls(TIMING_MODE=args.mode,TIMING_PERCENT=pct)
                say('Probe '+str(number)+'.')
                audio=render(new,word);add(audio);durations.append(len(audio))
            if not (durations[1]<durations[0]<len(before)):
                raise RuntimeError('The intended timing changes did not take effect for '+word)
        say('Pauto zum Vergleich, unverändert.')
        if render(new,'pauto')!=pauto:raise RuntimeError('The reference pauto changed')
        add(pauto)
    finally:
        for e in engines:e.close()
        for k in list(os.environ):
            if k.startswith(PREFIX):del os.environ[k]
        os.environ.update(saved)
    if sys.byteorder!='little':samples.byteswap()
    with wave.open(str(args.wav),'wb') as wav:
        wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(16000);wav.writeframes(samples.tobytes())
    print(f'Created {args.wav}: {len(samples)/16000:.1f} seconds, timing mode {args.mode}')


if __name__=='__main__':main()
