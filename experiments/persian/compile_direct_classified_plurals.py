"""Verify productive -یان plurals of recovered Persian word stems offline."""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

from compile_direct_lexicon import EXPECTED_DICT, digest, lexical_fingerprint, reference_words
from espeak_ng_probe import EspeakPhonemeProbe
from hybrid_fa_frontend import DirectFirstPersian
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_sequence_accepted, word_tag

HERE = Path(__file__).resolve().parent
WORDS = HERE / 'direct_fa_classified_words.inc'


def phones(tag):
    return re.sub(r'\.[012]|[`\[\]~ ]', '', tag)


def generate(api, voice, frontend):
    rows = [json.loads('[' + line.strip()[1:-2] + ']')
            for line in WORDS.read_text(encoding='utf8').splitlines()
            if line.strip().startswith('{')]
    bits, counts = bytearray((len(rows) + 7) // 8), Counter()
    for i, (stem, root, _nonfinal) in enumerate(rows):
        if not stem.endswith('ی') or not root.endswith('i]'):
            continue
        word = stem + 'ان'
        if frontend.analyze_direct(word) is not None:
            counts['already_native'] += 1
            continue
        try:
            raw = reference_words(api, word)
            lists = [value.strip('|').split('|') for value in raw]
            if any(value[0] == '_' or value[-1] == '_' for value in lists):
                counts['pause'] += 1
                continue
            tags = tuple(word_tag(value) for value in raw)
            if (tags[0] != tags[3] or tags[1] != tags[2] or
                any(phones(tag) != phones(root) + 'jan' for tag in tags)):
                counts['different_phones'] += 1
                continue
            value = tags[0].replace('~', ' ')
            if not native_sequence_accepted(value, voice._phonemes_for_probe(value)):
                counts['native_parser'] += 1
                continue
            bits[i // 8] |= 1 << (i % 8)
            counts['admitted'] += 1
        except (UnsupportedPronunciation, ValueError, IndexError):
            counts['unsupported'] += 1
    lines = ['/* Generated by compile_direct_classified_plurals.py; GPL-3.0-only.\n',
             ' * Admitted stems are aligned with the recovered classified table.\n',
             ' * ' + json.dumps(dict(sorted(counts.items())), sort_keys=True) + '\n',
             ' */\n#define RELOQ_FA_CLASSIFIED_PLURAL_FINGERPRINT 0x' + lexical_fingerprint(rows) + 'ULL\n',
             'static const unsigned char fa_classified_plural_mask[] = {\n']
    for i in range(0, len(bits), 16):
        lines.append('    ' + ', '.join(f'0x{x:02x}' for x in bits[i:i+16]) + ',\n')
    return ''.join((*lines, '};\n')), counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('native-library', 'espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_classified_plurals.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary changed')
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)
    try:
        with DirectFirstPersian(args.native_library, None, None, None) as frontend, \
             EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            content, counts = generate(api, voice, frontend)
    finally:
        voice.close()
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the plural admissions differ from the validated output')
    else:
        args.output.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps(dict(counts), sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
