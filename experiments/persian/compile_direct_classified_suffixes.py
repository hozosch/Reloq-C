"""Verify productive suffixes on recovered stems for the native Persian core.

Generated admission bits contain no complete derived words. They restrict
unspaced spelling, where a suffix boundary can otherwise be ambiguous. The
separate half-space rule needs no per-stem admission. The reference engine is
used only while generating this table, never by the resulting runtime.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

from compile_direct_lexicon import EXPECTED_DICT, digest, lexical_fingerprint, reference_words
from espeak_ng_probe import EspeakPhonemeProbe
from hybrid_fa_frontend import DirectFirstPersian
from text_frontend import UnsupportedPronunciation, native_sequence_accepted, word_tag

HERE = Path(__file__).resolve().parent
WORDS = HERE / 'direct_fa_classified_words.inc'
SUFFIXES = (('ها', 'ha'), ('های', 'haje'), ('هایی', 'hai'),
            ('تر', 'tAr'), ('ترین', 'tArin'))


def phones(tag):
    tag = re.sub(r"'([Aaeiou]):'", r'\1', tag)
    return re.sub(r'\.[012]|[`\[\]~ ]', '', tag)


def generate(api, voice, frontend, limit=None):
    rows = [json.loads('[' + line.strip()[1:-2] + ']')
            for line in WORDS.read_text(encoding='utf8').splitlines()
            if line.strip().startswith('{')]
    masks, counts, cache = bytearray(len(rows)), Counter(), {}
    for i, (stem, root, _) in enumerate(rows):
        if limit is not None and i >= limit:
            break
        if '~' in root:
            continue
        for bit, (suffix, sound) in enumerate(SUFFIXES):
            word = stem + suffix
            try:
                raw = reference_words(api, word)
                if any('_' in item.strip('|').split('|') for item in raw):
                    counts['pause'] += 1
                    continue
                tags = tuple(word_tag(item) for item in raw)
                if any(phones(tag) != phones(root) + sound for tag in tags):
                    counts['different_phones'] += 1
                    continue
                if frontend.analyze_direct(word) is not None:
                    counts['already_native'] += 1
                    continue
                value = tags[0]
                if value not in cache:
                    cache[value] = native_sequence_accepted(value, voice._phonemes_for_probe(value))
                if not cache[value]:
                    counts['native_parser'] += 1
                    continue
                masks[i] |= 1 << bit
                counts[suffix] += 1
            except (UnsupportedPronunciation, ValueError, IndexError):
                counts['unsupported'] += 1
        if (i+1) % 5000 == 0:
            print(f'Checked {i+1}/{len(rows)} recovered stems', flush=True)
    lines = ['/* Generated by compile_direct_classified_suffixes.py; GPL-3.0-only.\n',
             ' * Admissions are aligned with the recovered classified table.\n',
             ' * ' + json.dumps(dict(sorted(counts.items())), ensure_ascii=True) + '\n',
             ' */\n#define RELOQ_FA_CLASSIFIED_SUFFIX_FINGERPRINT 0x' + lexical_fingerprint(rows) + 'ULL\n',
             'static const unsigned char fa_classified_suffix_masks[] = {\n']
    for i in range(0, len(masks), 16):
        lines.append('    ' + ', '.join(f'0x{x:02x}' for x in masks[i:i+16]) + ',\n')
    return ''.join((*lines, '};\n')), counts


def main():
    from test_selected_probe import engine, set_confirmed_persian_probe
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('native-library', 'espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_classified_suffixes.inc')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--limit', type=int)
    args = parser.parse_args()
    if args.limit is not None and args.output == HERE / 'direct_fa_classified_suffixes.inc':
        parser.error('limited generation cannot overwrite the full suffix table')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary changed')
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)
    try:
        with DirectFirstPersian(args.native_library, None, None, None) as frontend, \
             EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            content, counts = generate(api, voice, frontend, args.limit)
    finally:
        voice.close()
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the suffix admissions differ from the validated output')
    else:
        args.output.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps(dict(counts), sort_keys=True, ensure_ascii=False), flush=True)


if __name__ == '__main__':
    main()
