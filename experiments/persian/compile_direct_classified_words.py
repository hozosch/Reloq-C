"""Recover formerly reference-spoken classified Persian words offline.

Only words absent from the existing native analysis are considered. The
recorded Lilak spelling inventory contains no pronunciations. The old
eSpeak path supplies readings in four contexts, which must agree in phone
content and must also be accepted by the native phone parser. This data is
compiled into the core; no eSpeak code or process is used at runtime.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

from compile_direct_lexicon import (EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest,
                                   is_persian_word, lexical_fingerprint, reference_words)
from espeak_ng_probe import EspeakPhonemeProbe
from hybrid_fa_frontend import DirectFirstPersian
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_sequence_accepted, word_tag

HERE = Path(__file__).resolve().parent
INVENTORY = HERE / 'direct_fa_stress_classes.inc'


def inventory():
    # Use exactly the normalized spellings already compiled from Lilak.
    # No pronunciation or POS inference is taken from that inventory.
    source = INVENTORY.read_text(encoding='utf8')
    source = source.split('static const char *const fa_stress_banks[]', 1)[0]
    return sorted({m.group(1) for m in re.finditer(r'^\s*"([^"\\]+)\\0";?$', source, re.M)
                   if is_persian_word(m.group(1))}, key=lambda value: value.encode('utf8'))


def generate(api, voice, frontend):
    candidates = inventory()
    rows, outcomes, parser_cache = [], Counter(), {}
    for index, word in enumerate(candidates, 1):
        if frontend.analyze_direct(word) is not None:
            outcomes['already_native'] += 1
            continue
        try:
            raw = reference_words(api, word)
            phones = [value.strip('|').split('|') for value in raw]
            if any(value[0] == '_' or value[-1] == '_' for value in phones):
                outcomes['word_edge_pause'] += 1
                continue
            tags = tuple(word_tag(value) for value in raw)
            if (tags[0] != tags[3] or tags[1] != tags[2] or
                    re.sub(r'\.[012]', '.', tags[0]) != re.sub(r'\.[012]', '.', tags[1])):
                outcomes['context_dependent'] += 1
                continue
            for tag in set(tags):
                if tag not in parser_cache:
                    value = tag.replace('~', ' ')
                    parser_cache[tag] = native_sequence_accepted(value, voice._phonemes_for_probe(value))
                if not parser_cache[tag]:
                    break
            else:
                rows.append((word, tags[0], tags[1]))
                continue
            outcomes['native_parser'] += 1
        except (UnsupportedPronunciation, IndexError, ValueError):
            outcomes['unsupported'] += 1
        finally:
            if index % 5000 == 0:
                print(f'Checked {index}/{len(candidates)}; recovered {len(rows)}', flush=True)
    metadata = {'inventory_sha256': digest(INVENTORY), 'fa_dict_sha256': EXPECTED_DICT,
                'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'], 'candidates': len(candidates),
                'admitted': len(rows), 'rejected': dict(sorted(outcomes.items()))}
    lines = ['/* Generated by compile_direct_classified_words.py; GPL-3.0-only.\n',
             ' * Lilak spelling inventory: Apache-2.0; see reference-lilak/persian.\n',
             ' * eSpeak NG Persian rules: GPL-3.0-or-later; see reference-espeak/persian.\n',
             ' * ' + json.dumps(metadata, sort_keys=True, ensure_ascii=True) + '\n',
             ' */\n#define RELOQ_FA_CLASSIFIED_FINGERPRINT 0x' + lexical_fingerprint(rows) + 'ULL\n',
             'static const struct fa_context_entry fa_classified_entries[] = {\n']
    for row in rows:
        lines.append('    {' + ', '.join(json.dumps(value, ensure_ascii=False) for value in row) + '},\n')
    return ''.join((*lines, '};\n')), metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('native-library', 'espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_classified_words.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if any(digest(SOURCE / name) != value for name, value in EXPECTED_SOURCES.items()):
        raise RuntimeError('the pinned Persian reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary changed')
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)
    try:
        with DirectFirstPersian(args.native_library, None, None, None) as frontend, \
             EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            content, metadata = generate(api, voice, frontend)
    finally:
        voice.close()
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the classified table differs from the validated output')
    else:
        args.output.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps(metadata, sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
