"""Generate validated Persian ending rules and compact per-stem admissions."""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path

from compile_direct_lexicon import EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest, lexical_fingerprint, reference_tags
from compile_direct_plural import LEXICON, entries
from direct_fa_extended_suffix_rules import SUFFIXES, candidate
from espeak_ng_probe import EspeakPhonemeProbe
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_tag_accepted

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--espeak-library', required=True, type=Path)
    parser.add_argument('--data-parent', required=True, type=Path)
    parser.add_argument('--probe', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_extended_suffixes.inc')
    args = parser.parse_args()
    for name, expected in EXPECTED_SOURCES.items():
        if digest(SOURCE / name) != expected:
            raise RuntimeError('the Persian reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the Persian reference dictionary changed')
    rows = list(entries())
    bitmaps = [[bytearray((len(rows) + 7) // 8) for _ in range(2)] for _ in SUFFIXES]
    admitted = Counter()
    voice = engine(args.probe, 0x90000)
    pending = []
    pending_bytes = 0

    def accept(index, kind, mode):
        bitmaps[kind][mode][index // 8] |= 1 << (index % 8)
        admitted[SUFFIXES[kind]] += 1

    def flush():
        nonlocal pending_bytes
        if not pending:
            return
        for index, kind, mode, tag in pending:
            # A tag must also be accepted on its own; surrounding tags may
            # otherwise mask a parser failure at a word boundary.
            if native_tag_accepted(tag, voice._phonemes_for_probe(tag)):
                accept(index, kind, mode)
        pending.clear()
        pending_bytes = 0

    try:
        set_confirmed_persian_probe(d=2, z=2)
        with EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            for index, (stem, base) in enumerate(rows):
                if '\u200c' in stem:
                    continue
                for kind, suffix in enumerate(SUFFIXES):
                    candidates = tuple(candidate(base, kind, mode) for mode in range(2))
                    if not any(candidates):
                        continue
                    try:
                        reference = reference_tags(api, stem + suffix)
                        if len(set(reference)) != 1:
                            continue
                        mode = next((mode for mode, tag in enumerate(candidates) if tag == reference[0]), None)
                        if mode is None:
                            continue
                    except UnsupportedPronunciation:
                        continue
                    tag = candidates[mode]
                    if len(pending) >= 32 or pending_bytes + len(tag) > 1500:
                        flush()
                    pending.append((index, kind, mode, tag))
                    pending_bytes += len(tag) + 1
                if index and index % 1000 == 0:
                    print(f'Checked {index}/{len(rows)} Persian stems', flush=True)
            flush()
    finally:
        voice.close()
    if any(admitted[suffix] < 100 for suffix in SUFFIXES):
        raise RuntimeError('unexpectedly low suffix admission; no table written')
    meta = {'lexicon_sha256': digest(LEXICON), 'fa_dict_sha256': EXPECTED_DICT,
            'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'], 'probe_sha256': digest(args.probe),
            'bases': len(rows), 'admitted': dict(admitted)}
    lines = ['/* Generated by compile_direct_extended_suffixes.py; GPL-3.0-or-later.\n',
             ' * ' + json.dumps(meta, sort_keys=True, ensure_ascii=True) + '\n',
             ' */\n',
             '#if RELOQ_FA_LEXICON_FINGERPRINT != 0x' + lexical_fingerprint(rows) + 'ULL\n',
             '#error Persian extended suffixes must be regenerated for this lexicon\n',
             '#endif\n',
             f'static const unsigned char fa_extended_suffix_bases[{len(SUFFIXES)}][2][{len(bitmaps[0][0])}] = {{\n']
    for modes in bitmaps:
        lines.append('  {\n')
        for bitmap in modes:
            lines.append('    {\n')
            for offset in range(0, len(bitmap), 16):
                lines.append('      ' + ', '.join(f'0x{value:02x}' for value in bitmap[offset:offset + 16]) + ',\n')
            lines.append('    },\n')
        lines.append('  },\n')
    lines.append('};\n')
    temporary = args.output.with_name(args.output.name + '.tmp')
    temporary.write_text(''.join(lines), encoding='utf8', newline='\n')
    temporary.replace(args.output)
    print(json.dumps(meta, sort_keys=True, ensure_ascii=True), flush=True)


if __name__ == '__main__':
    main()
