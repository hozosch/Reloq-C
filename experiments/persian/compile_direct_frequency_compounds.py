"""Verify productive compound endings for native frequency-table stems.

The generated admission bits let the native rules handle combinations that
are absent from the source word list. Each stem/ending pair must agree with
the reference in four positions and be accepted by the native phone parser.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path

from compile_direct_lexicon import (EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest,
                                   lexical_fingerprint, reference_tags)
from direct_fa_compound_rules import SUFFIXES, candidate
from espeak_ng_probe import EspeakPhonemeProbe
from test_direct_frequency_words import entries
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_tag_accepted

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, required=True, type=Path)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_frequency_compounds.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if any(digest(SOURCE / name) != expected for name, expected in EXPECTED_SOURCES.items()):
        raise RuntimeError('the pinned Persian reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian reference dictionary changed')
    rows = list(entries())
    masks, admitted, cache = bytearray(len(rows)), Counter(), {}
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)

    def accepted(tag):
        if tag not in cache:
            cache[tag] = native_tag_accepted(tag, voice._phonemes_for_probe(tag))
        return cache[tag]

    try:
        with EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('compound admission requires eSpeak NG 1.53.0')
            for index, (stem, final_base, nonfinal_base) in enumerate(rows):
                if '\u200c' not in stem and final_base == nonfinal_base:
                    for kind, suffix in enumerate(SUFFIXES):
                        final = candidate(final_base, kind, False)
                        nonfinal = candidate(final_base, kind, True)
                        if final is None or nonfinal is None:
                            continue
                        try:
                            if reference_tags(api, stem + suffix) != (final, nonfinal, nonfinal, final):
                                continue
                            if not all(accepted(tag) for tag in {final, nonfinal}):
                                continue
                        except (UnsupportedPronunciation, IndexError):
                            continue
                        masks[index] |= 1 << kind
                        admitted[suffix] += 1
                if (index + 1) % 2000 == 0:
                    print(f'Checked {index + 1}/{len(rows)} compound stems', flush=True)
    finally:
        voice.close()
    if any(admitted[suffix] < 50 for suffix in SUFFIXES):
        raise RuntimeError('unexpectedly few verified compounds; no table written')
    metadata = {'bases': len(rows), 'frequency_fingerprint': lexical_fingerprint(rows),
                'fa_dict_sha256': EXPECTED_DICT, 'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'],
                'admitted': dict(admitted)}
    lines = ['/* Generated by compile_direct_frequency_compounds.py; GPL-3.0-only.\n',
             ' * ' + json.dumps(metadata, sort_keys=True, ensure_ascii=True) + '\n',
             ' */\n#if RELOQ_FA_FREQUENCY_FINGERPRINT != 0x' + lexical_fingerprint(rows) + 'ULL\n',
             '#error Persian frequency compounds must be regenerated for this word table\n',
             '#endif\nstatic const unsigned char fa_frequency_compound_masks[] = {\n']
    for offset in range(0, len(masks), 16):
        lines.append('    ' + ', '.join(f'0x{value:02x}' for value in masks[offset:offset + 16]) + ',\n')
    lines.append('};\n')
    content = ''.join(lines)
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the compound admissions differ from the validated output')
    else:
        args.output.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps(metadata, sort_keys=True, ensure_ascii=True), flush=True)


if __name__ == '__main__':
    main()
