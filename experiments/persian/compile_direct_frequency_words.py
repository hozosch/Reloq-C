"""Generate native Persian word readings from a public frequency inventory.

The eSpeak reader is an offline reference only. Each admitted word must have
aligned readings in four contexts, no word-edge pause, and phonemes accepted
unchanged by the native Persian parser. Existing direct rules retain priority.
"""
from __future__ import annotations

import argparse
from collections import Counter
import ctypes
import json
from pathlib import Path
import re

from compile_direct_lexicon import (EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest,
                                   is_persian_word, lexical_fingerprint, reference_words)
from compile_direct_pause_words import normalized
from compile_direct_recovered_words import EXTRA_SYMBOL_NAME_WORDS
from espeak_ng_probe import EspeakPhonemeProbe
from hybrid_fa_frontend import DirectFirstPersian
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_sequence_accepted, word_tag

HERE = Path(__file__).resolve().parent
INVENTORY = HERE.parents[1] / 'reference-frequency/persian/fa_50k.txt'
EXPECTED_INVENTORY = '96ea178f77022cdb2d358feb75a4fc474754daa224a4beba296ad777a514bdf7'


def generate(api, native, normalize_dll, frontend):
    candidates, outcomes, parser_cache = Counter(), Counter(), {}
    for line in INVENTORY.read_text(encoding='utf8').splitlines():
        if not line.strip():
            continue
        word, count = line.rsplit(' ', 1)
        if not is_persian_word(word):
            continue
        word = normalized(normalize_dll, word)
        if is_persian_word(word):
            candidates[word] += int(count)
    rows = []
    for index, (word, count) in enumerate(sorted(candidates.items(), key=lambda x: x[0].encode('utf8')), 1):
        if word in EXTRA_SYMBOL_NAME_WORDS or frontend.analyze_direct(word) is not None:
            outcomes['already_native_words'] += 1
            outcomes['already_native_occurrences'] += count
            continue
        try:
            raw = reference_words(api, word)
            phones = [value.strip('|').split('|') for value in raw]
            if any(value[0] == '_' or value[-1] == '_' for value in phones):
                outcomes['word_edge_pause'] += 1
                continue
            tags = tuple(word_tag(value) for value in raw)
            if (tags[0] != tags[3] or tags[1] != tags[2] or
                    re.sub(r'\.[012]', '.', tags[0]) != re.sub(r'\.[012]', '.', tags[1])):
                outcomes['context_dependent'] += 1
                continue
            for tag in set(tags):
                if tag not in parser_cache:
                    value = tag.replace('~', ' ')
                    parser_cache[tag] = native_sequence_accepted(value, native._phonemes_for_probe(value))
                if not parser_cache[tag]:
                    break
            else:
                rows.append((word, tags[0], tags[1]))
                outcomes['new_native_occurrences'] += count
                continue
            outcomes['native_parser'] += 1
        except (UnsupportedPronunciation, IndexError, ValueError) as error:
            outcomes['unsupported'] += 1
        finally:
            if index % 5000 == 0:
                print(f'Checked {index}/{len(candidates)} words; {len(rows)} newly covered', flush=True)
    if len(rows) < 1000:
        raise RuntimeError('unexpectedly few validated frequency words')
    metadata = {'inventory_sha256': EXPECTED_INVENTORY, 'fa_dict_sha256': EXPECTED_DICT,
                'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'], 'candidates': len(candidates),
                'admitted': len(rows), 'counts': dict(sorted(outcomes.items()))}
    lines = ['/* Generated by compile_direct_frequency_words.py; GPL-3.0-only.\n',
             ' * FrequencyWords Persian 2018 inventory: CC BY-SA 4.0, Hermit Dave and contributors.\n',
             ' * eSpeak NG Persian rules: GPL-3.0-or-later. See reference-frequency/persian.\n',
             ' * ' + json.dumps(metadata, sort_keys=True, ensure_ascii=True) + '\n',
             ' */\n#define RELOQ_FA_FREQUENCY_FINGERPRINT 0x' + lexical_fingerprint(rows) + 'ULL\n',
             'static const struct fa_context_entry fa_frequency_entries[] = {\n']
    for word, final, nonfinal in rows:
        lines.append('    {' + ', '.join(json.dumps(value, ensure_ascii=False)
                                        for value in (word, final, nonfinal)) + '},\n')
    return ''.join((*lines, '};\n')), metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('native-library', 'normalizer-library', 'espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_frequency_words.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if digest(INVENTORY) != EXPECTED_INVENTORY or any(digest(SOURCE / name) != value
                                                       for name, value in EXPECTED_SOURCES.items()):
        raise RuntimeError('the pinned reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary changed')
    normalize_dll = ctypes.CDLL(str(args.normalizer_library.resolve()))
    normalize_dll.reloq_fa_direct_normalize.argtypes = (ctypes.c_char_p, ctypes.c_size_t,
        ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.POINTER(ctypes.c_size_t)),
        ctypes.POINTER(ctypes.c_size_t))
    normalize_dll.reloq_fa_direct_normalize.restype = ctypes.c_int
    normalize_dll.reloq_fa_direct_free.argtypes = (ctypes.c_void_p,)
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)
    try:
        with DirectFirstPersian(args.native_library, None, None, None) as frontend, \
             EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            content, metadata = generate(api, voice, normalize_dll, frontend)
    finally:
        voice.close()
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the frequency table differs from the validated output')
    else:
        args.output.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps(metadata, sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
