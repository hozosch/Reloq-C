"""Verify productive Persian suffix boundaries for the existing word tables.

The generated bits admit stem/ending combinations, not complete word fixes.
Only forms whose reference phones preserve the established stem are admitted.
The reference is used offline; the C runtime does not load eSpeak.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

from compile_direct_lexicon import EXPECTED_DICT, digest, lexical_fingerprint, reference_words
from compile_direct_plural import entries as main_entries
from espeak_ng_probe import EspeakPhonemeProbe
from hybrid_fa_frontend import DirectFirstPersian
from test_direct_frequency_words import entries as frequency_entries
from text_frontend import UnsupportedPronunciation, native_sequence_accepted, word_tag

HERE = Path(__file__).resolve().parent
SUFFIXES = (('ها', 'ha'), ('های', 'haje'), ('هایی', 'hai'),
            ('تر', 'tAr'), ('ترین', 'tArin'), ('هایم', 'hajAm'),
            ('هایت', 'hajAt'), ('هایش', 'hajAS'))


def phones(tag):
    tag = re.sub(r"'([Aaeiou]):'", r'\1', tag)
    return re.sub(r'\.[012]|[`\[\]~ ]', '', tag)


def generate(api, voice, frontend):
    tables = (('main', list(main_entries())), ('frequency', list(frequency_entries())))
    results, counts, parser_cache = [], Counter(), {}
    for table_name, rows in tables:
        masks = bytearray(len(rows))
        for i, row in enumerate(rows):
            stem = row[0]
            if len(stem) < 2 or '\u200c' in stem:
                continue
            base = frontend.analyze_direct(stem)
            if not base or len(base.parts) != 1:
                continue
            root = base.parts[0].text
            if '~' in root or not root.startswith('`[') or not root.endswith(']'):
                continue
            for bit, (suffix, spoken) in enumerate(SUFFIXES):
                word = stem + suffix
                # The runtime also checks whole words first. Avoid recording
                # admissions for already covered forms in the baseline.
                if frontend.analyze_direct(word) is not None:
                    counts[table_name + '_already_native'] += 1
                    continue
                try:
                    raw = reference_words(api, word)
                    if any('_' in item.strip('|').split('|') for item in raw):
                        counts[table_name + '_pause'] += 1
                        continue
                    tags = tuple(word_tag(item) for item in raw)
                    if any(phones(tag) != phones(root) + spoken for tag in tags):
                        counts[table_name + '_different_phones'] += 1
                        continue
                    tag = tags[0]
                    if tag not in parser_cache:
                        parser_cache[tag] = native_sequence_accepted(tag, voice._phonemes_for_probe(tag))
                    if not parser_cache[tag]:
                        counts[table_name + '_native_parser'] += 1
                        continue
                    masks[i] |= 1 << bit
                    counts[table_name + '_' + suffix] += 1
                except (UnsupportedPronunciation, ValueError, IndexError):
                    counts[table_name + '_unsupported'] += 1
            if (i + 1) % 5000 == 0:
                print(f'Checked {i+1}/{len(rows)} {table_name} stems', flush=True)
        results.append((table_name, rows, masks))
    lines = ['/* Generated by compile_direct_nominal_suffixes.py; GPL-3.0-only.\n',
             ' * Four reference contexts must preserve the existing stem phones.\n',
             ' * ' + json.dumps(dict(sorted(counts.items())), ensure_ascii=True) + '\n',
             ' */\n']
    for name, rows, masks in results:
        expected = 'RELOQ_FA_LEXICON_FINGERPRINT' if name == 'main' else 'RELOQ_FA_FREQUENCY_FINGERPRINT'
        if name == 'frequency':
            lines.append('#ifndef RELOQ_FA_EXCLUDE_FREQUENCY_WORDS\n')
        lines.extend((f'#if {expected} != 0x{lexical_fingerprint(rows)}ULL\n',
                      '#error Persian nominal suffix admissions require the same word table\n',
                      '#endif\n', f'static const unsigned char fa_nominal_{name}_masks[] = {{\n'))
        for i in range(0, len(masks), 16):
            lines.append('    ' + ', '.join(f'0x{x:02x}' for x in masks[i:i+16]) + ',\n')
        lines.append('};\n')
        if name == 'frequency':
            lines.append('#endif\n')
    return ''.join(lines), counts


def main():
    from test_selected_probe import engine, set_confirmed_persian_probe
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ('native-library', 'espeak-library', 'data-parent', 'probe'):
        parser.add_argument('--' + option, type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_nominal_suffixes.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary changed')
    set_confirmed_persian_probe()
    voice = engine(args.probe, 0x90000)
    try:
        with DirectFirstPersian(args.native_library, None, None, None) as frontend, \
             EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('these admissions require eSpeak NG 1.53.0')
            content, counts = generate(api, voice, frontend)
    finally:
        voice.close()
    if args.check:
        if args.output.read_text(encoding='utf8') != content:
            raise RuntimeError('the nominal suffix admissions differ')
    else:
        temporary = args.output.with_suffix('.inc.tmp')
        temporary.write_text(content, encoding='utf8', newline='\n')
        temporary.replace(args.output)
    print(json.dumps(dict(counts), ensure_ascii=False, sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
