"""Generate direct Persian 0..999 phone groups from a pinned eSpeak reference.

This offline generator uses eSpeak for pronunciation and a native Finnish
phone parser to validate the resulting tags. The emitted C data does not use
eSpeak at runtime. Composition of larger numbers is implemented separately.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from compile_direct_lexicon import EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest
from espeak_ng_probe import EspeakPhonemeProbe
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import native_tag_accepted, word_tag

HERE = Path(__file__).resolve().parent


def phones(api, text):
    clauses = api.translate(text, separator='|')
    if len(clauses) != 1:
        raise RuntimeError(f'unexpected number of clauses in {text!r}')
    return clauses[0].phonemes.strip().split()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--espeak-library', type=Path, required=True)
    parser.add_argument('--data-parent', type=Path, required=True)
    parser.add_argument('--probe', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_numbers.inc')
    args = parser.parse_args()
    for name, expected in EXPECTED_SOURCES.items():
        if digest(SOURCE / name) != expected:
            raise RuntimeError('the pinned Persian sources differ')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the pinned Persian dictionary differs')
    native = engine(args.probe, 0x90000)
    groups = []
    try:
        set_confirmed_persian_probe()
        with EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('the number data require eSpeak NG 1.53.0')
            for number in range(1000):
                word = str(number)
                isolated = phones(api, word)
                # These contexts verify that a fixed number group is not
                # admitted when eSpeak changes it next to other words.
                if (phones(api, word + ' آمد.')[:-1] != isolated or
                    phones(api, 'من ' + word + ' آمد.')[1:-1] != isolated or
                    phones(api, 'من ' + word + '.')[1:] != isolated):
                    raise RuntimeError(f'context-dependent number {number}')
                tags = [word_tag(token) for token in isolated]
                if not all(native_tag_accepted(tag, native._phonemes_for_probe(tag)) for tag in tags):
                    raise RuntimeError(f'number tag rejected by native parser: {number}')
                groups.append(' '.join(tags))
            scales = []
            for value in (1000, 1000000, 1000000000):
                final = phones(api, str(value))[-1]
                # Take the scale with its linking vowel from an example with
                # a following nonzero group. Ignore eSpeak's pause marker.
                following = phones(api, str(value + 234))[1].replace('|_!', '')
                final_tag, followed_tag = word_tag(final), word_tag(following)
                if not all(native_tag_accepted(tag, native._phonemes_for_probe(tag))
                           for tag in (final_tag, followed_tag)):
                    raise RuntimeError(f'scale tag rejected by native parser: {value}')
                scales.append((final_tag, followed_tag))
            decimal = word_tag(phones(api, '3.14')[1])
            if not native_tag_accepted(decimal, native._phonemes_for_probe(decimal)):
                raise RuntimeError('decimal marker tag rejected by native parser')
    finally:
        native.close()
    metadata = {'espeak_version': '1.53.0', 'fa_dict_sha256': EXPECTED_DICT,
                'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'],
                'native_probe_sha256': digest(args.probe), 'groups': len(groups)}
    lines = ['/* Generated by compile_direct_numbers.py; GPL-3.0-or-later.\n',
             ' * Reference: eSpeak NG Persian; see reference-espeak/persian.\n',
             ' * ' + json.dumps(metadata, sort_keys=True) + '\n', ' */\n',
             'static const char *const fa_number_groups[] = {\n']
    lines.extend('    ' + json.dumps(tag) + ',\n' for tag in groups)
    lines.append('};\nstatic const char *const fa_number_scales[][2] = {\n')
    lines.extend('    {' + json.dumps(final) + ', ' + json.dumps(followed) + '},\n'
                 for final, followed in scales)
    lines.append('};\nstatic const char fa_number_decimal[] = ' + json.dumps(decimal) + ';\n')
    temporary = args.output.with_name(args.output.name + '.tmp')
    temporary.write_text(''.join(lines), encoding='utf8', newline='\n')
    temporary.replace(args.output)
    print(json.dumps(metadata, sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
