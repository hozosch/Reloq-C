"""Generate a conservative admission bitmap for the direct ZWNJ + ها rule.

Each admitted stem must already be an invariant complete-word entry. The
reference must produce the stem's existing phones plus the two supported
suffix stress forms in four positions, and the native parser must accept
both resulting tags. No eSpeak dependency is used by the generated rule.
This does not claim to implement all Persian morphology or all uses of ها.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from compile_direct_lexicon import EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, digest, lexical_fingerprint, reference_tags
from espeak_ng_probe import EspeakPhonemeProbe
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_tag_accepted

HERE = Path(__file__).resolve().parent
LEXICON = HERE / 'direct_fa_lexicon.inc'


def entries():
    for line in LEXICON.read_text(encoding='utf8').splitlines():
        line = line.strip()
        if line.startswith('{') and line.endswith('},'):
            yield tuple(json.loads('[' + line[1:-2] + ']'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--espeak-library', type=Path, required=True)
    parser.add_argument('--data-parent', type=Path, required=True)
    parser.add_argument('--probe', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_plural.inc')
    args = parser.parse_args()
    for name, expected in EXPECTED_SOURCES.items():
        if digest(SOURCE / name) != expected:
            raise RuntimeError('the Persian reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the Persian reference dictionary changed')
    rows = list(entries())
    bitmap = bytearray((len(rows) + 7) // 8)
    admitted = 0
    native = engine(args.probe, 0x90000)
    try:
        set_confirmed_persian_probe()
        with EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            for i, (stem, base) in enumerate(rows):
                if '\u200c' in stem or not base.endswith(']'):
                    continue
                final, nonfinal = base[:-1] + '.1ha]', base[:-1] + '.0ha]'
                try:
                    tags = reference_tags(api, stem + '\u200cها')
                    if tags != (final, nonfinal, nonfinal, final):
                        continue
                    if not all(native_tag_accepted(tag, native._phonemes_for_probe(tag))
                               for tag in (final, nonfinal)):
                        continue
                except UnsupportedPronunciation:
                    continue
                bitmap[i // 8] |= 1 << (i % 8)
                admitted += 1
                if i and i % 3000 == 0:
                    print(f'Checked {i}/{len(rows)} bases', flush=True)
    finally:
        native.close()
    if not admitted:
        raise RuntimeError('no suffix bases admitted; no table written')
    meta = {'lexicon_sha256': digest(LEXICON), 'fa_dict_sha256': EXPECTED_DICT,
            'probe_sha256': digest(args.probe), 'bases': len(rows), 'admitted': admitted}
    lines = ['/* Generated by compile_direct_plural.py; GPL-3.0-or-later.\n',
             ' * Reference: eSpeak NG Persian; see reference-espeak/persian.\n',
             ' * ' + json.dumps(meta, sort_keys=True) + '\n',
             ' */\n',
             '#if RELOQ_FA_LEXICON_FINGERPRINT != 0x' + lexical_fingerprint(rows) + 'ULL\n',
             '#error Persian plural rule must be regenerated for this lexicon\n',
             '#endif\n',
             'static const unsigned char fa_plural_zwnj_bases[] = {\n']
    for offset in range(0, len(bitmap), 16):
        lines.append('    ' + ', '.join(f'0x{value:02x}' for value in bitmap[offset:offset + 16]) + ',\n')
    lines.append('};\n')
    temporary = args.output.with_name(args.output.name + '.tmp')
    temporary.write_text(''.join(lines), encoding='utf8', newline='\n')
    temporary.replace(args.output)
    print(json.dumps(meta, sort_keys=True), flush=True)


if __name__ == '__main__':
    main()
