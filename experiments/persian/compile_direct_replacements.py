"""Transfer eSpeak's Persian .replace patterns to static native C data."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'reference-espeak/persian/fa_rules'
OUTPUT = Path(__file__).with_name('direct_fa_replacements.inc')


def replacements(source: Path) -> tuple[tuple[int, str], ...]:
    active = False
    seen = {}
    for line_number, raw in enumerate(source.read_text(encoding='utf8').splitlines(), 1):
        line = raw.split('//', 1)[0].strip()
        if not line:
            continue
        if line == '.replace':
            if active or seen:
                raise ValueError('duplicate replacement section')
            active = True
            continue
        if active and line.startswith('.'):
            active = False
            break
        if not active:
            continue
        fields = line.split()
        if not 1 <= len(fields) <= 2 or len(fields[0]) != 1:
            raise ValueError(f'unsupported replacement at line {line_number}')
        source_cp = ord(fields[0])
        target = fields[1] if len(fields) == 2 else ''
        if (len(target) > 2 or len(target.encode('utf8')) > 2 * len(fields[0].encode('utf8'))
                or source_cp in seen):
            raise ValueError(f'ambiguous replacement at line {line_number}')
        seen[source_cp] = target
    if active or not seen:
        raise ValueError('missing or unterminated replacement section')
    return tuple(sorted(seen.items()))


def render(source: Path) -> str:
    rows = replacements(source)
    fingerprint = hashlib.sha256(source.read_bytes()).hexdigest()
    output = [
        '/* Generated by compile_direct_replacements.py from eSpeak NG\n',
        ' * fa_rules by Shadyar Khodayari, GPL-3.0-or-later.\n',
        f' * fa_rules SHA-256: {fingerprint}\n',
        ' */\n',
        'static const struct fa_replacement fa_replacements[] = {\n',
    ]
    output.extend(f'    {{0x{cp:04x}u, {json.dumps(value, ensure_ascii=False)}}},\n'
                  for cp, value in rows)
    output.append('};\n')
    return ''.join(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=SOURCE)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(args.source)
    if args.check:
        if args.output.read_text(encoding='utf8') != expected:
            raise SystemExit('generated replacement table is stale')
    else:
        args.output.write_text(expected, encoding='utf8', newline='\n')
    print(f'{len(replacements(args.source))} direct Persian replacement patterns verified.')


if __name__ == '__main__':
    main()
