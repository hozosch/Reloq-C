"""Compile verified ezafe spellings and common marked text from eSpeak.

GPL-3.0-or-later. Each entry is checked in four sentence positions and
against the native phoneme parser. Unverified spellings retain the reference
fallback; a combining mark is never discarded just to make a word fit.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from compile_direct_lexicon import EXPECTED_DICT, EXPECTED_SOURCES, SOURCE, checked_tag, digest, lexical_fingerprint
from compile_direct_plural import entries
from espeak_ng_probe import EspeakPhonemeProbe
from test_selected_probe import engine, set_confirmed_persian_probe
from text_frontend import UnsupportedPronunciation, native_tag_accepted

HERE = Path(__file__).resolve().parent
from direct_fa_vocalized_rules import EXTRA, candidate

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--espeak-library', required=True, type=Path)
    parser.add_argument('--data-parent', required=True, type=Path)
    parser.add_argument('--probe', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_vocalized.inc')
    args = parser.parse_args()
    if any(digest(SOURCE / name) != value for name, value in EXPECTED_SOURCES.items()):
        raise RuntimeError('the Persian reference sources changed')
    if digest(args.data_parent / 'espeak-ng-data/fa_dict') != EXPECTED_DICT:
        raise RuntimeError('the Persian reference dictionary changed')
    rows = list(entries())
    bases = {stem + '\u0650': (i, tag) for i, (stem, tag) in enumerate(rows)
             if '\u200c' not in stem and len(stem) > 1}
    candidates = set(EXTRA) | set(bases)
    bitmaps = [bytearray((len(rows) + 7) // 8) for _ in range(2)]
    selected, exceptions = [], []
    voice = engine(args.probe, 0x90000)
    try:
        set_confirmed_persian_probe(d=2, z=2)
        with EspeakPhonemeProbe(args.espeak_library, args.data_parent) as api:
            if api.version != '1.53.0':
                raise RuntimeError('this table requires eSpeak NG 1.53.0')
            for index, word in enumerate(sorted(candidates)):
                try:
                    tag = checked_tag(api, word)
                    if not native_tag_accepted(tag, voice._phonemes_for_probe(tag)):
                        continue
                except UnsupportedPronunciation:
                    continue
                selected.append((word, tag))
                found = bases.get(word)
                if found is not None:
                    stem_index, base = found
                    for mode in (0, 1):
                        if candidate(base, mode) == tag:
                            bitmaps[mode][stem_index // 8] |= 1 << (stem_index % 8)
                            break
                    else:
                        exceptions.append((word, tag))
                else:
                    exceptions.append((word, tag))
                if index and index % 2000 == 0:
                    print(f'Checked {index}/{len(candidates)} vocalized forms', flush=True)
    finally:
        voice.close()
    if not set(EXTRA) <= {word for word, _ in selected}:
        raise RuntimeError('a required example did not pass reference validation')
    meta = {'fa_dict_sha256': EXPECTED_DICT, 'fa_rules_sha256': EXPECTED_SOURCES['fa_rules'],
            'candidates': len(candidates), 'admitted': len(selected),
            'exceptions': len(exceptions)}
    lines = ['/* Generated by compile_direct_vocalized.py; GPL-3.0-or-later.\n',
             ' * ' + json.dumps(meta, sort_keys=True) + '\n */\n',
             '#if RELOQ_FA_LEXICON_FINGERPRINT != 0x' + lexical_fingerprint(rows) + 'ULL\n',
             '#error Persian vocalized rules must be regenerated for this lexicon\n',
             '#endif\n',
             f'static const unsigned char fa_vocalized_modes[2][{len(bitmaps[0])}] = {{\n']
    for bitmap in bitmaps:
        lines.append('  {\n')
        for offset in range(0, len(bitmap), 16):
            lines.append('    ' + ', '.join(f'0x{value:02x}' for value in bitmap[offset:offset + 16]) + ',\n')
        lines.append('  },\n')
    lines.extend(('};\n', 'static const struct fa_direct_entry fa_vocalized_entries[] = {\n'))
    for word, tag in exceptions:
        lines.append('    {' + json.dumps(word, ensure_ascii=False) + ', ' + json.dumps(tag) + '},\n')
    lines.append('};\n')
    temp = args.output.with_name(args.output.name + '.tmp')
    temp.write_text(''.join(lines), encoding='utf8', newline='\n')
    temp.replace(args.output)
    print(json.dumps(meta, sort_keys=True), flush=True)

if __name__ == '__main__':
    main()
