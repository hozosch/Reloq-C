"""Generate a bounded Persian place-name class for demonym stress."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
SHA256 = '75f4d297a03b8c6a76cdee7c51706bc585495035d5ef1e9d8a115205e5805457'


def compile_names(source: Path) -> str:
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('Persian city source does not match its recorded revision')
    data = json.loads(raw.decode('utf8'))
    if not isinstance(data, list):
        raise ValueError('invalid Persian city source')
    table = str.maketrans({'ك': 'ک', 'ي': 'ی', 'ى': 'ی', 'ـ': ''})
    names = set()
    for entry in data:
        if not isinstance(entry, dict) or not isinstance(entry.get('name'), str):
            raise ValueError('invalid Persian city name')
        name = unicodedata.normalize('NFC', entry['name']).translate(table)
        if not name or any(c in name for c in '\0\n\r"\\'):
            raise ValueError('unsafe Persian city name')
        names.add(name)
    lines = ['/* Generated by compile_fa_city_stems.py; GPL-3.0.',
             ' * Source and provenance: reference-persian-cities/README.md. */',
             'static const char *const fa_city_stems[] = {']
    lines.extend('    "' + name + '",' for name in sorted(names, key=lambda x: x.encode('utf8')))
    lines.extend(('};', ''))
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'reference-persian-cities/iran-cities-filtered.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'experiments/persian/direct_fa_city_stems.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = compile_names(args.source)
    if args.check:
        if args.output.read_text(encoding='utf8') != value:
            raise SystemExit('Persian city stems need regeneration')
    else:
        args.output.write_text(value, encoding='utf8', newline='\n')
    print('Checked' if args.check else 'Generated', 'Persian city stems.')


if __name__ == '__main__':
    main()
