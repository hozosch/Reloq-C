"""Compile word classes from the Apache-2.0 Lilak Persian lexicon.

The result contains only spelling and coarse part of speech, not any
pronunciation. The native code applies the independently documented stress
rules conservatively and leaves ambiguous categories unchanged.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path
import unicodedata

HERE = Path(__file__).resolve().parent
SOURCE_SHA256 = '4eeb621442cf38d6d9aac2923daced2b8ae17c770773a7260a02f3c3957daff6'
LEXICAL = {'noun_singular', 'noun_plural', 'adjective', 'adverb', 'numeral',
           'adjective_comparative', 'adjective_superlative'}


def word_records(source: Path):
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError('Lilak source does not match the recorded revision')
    words, categories = {}, {}
    for row in csv.reader(line for line in data.decode('utf8').splitlines()
                          if line and not line.startswith('#')):
        if len(row) < 2:
            continue
        word = unicodedata.normalize('NFC', row[0]).translate(
            str.maketrans({'ك': 'ک', 'ي': 'ی', 'ى': 'ی', 'ـ': ''}))
        if not word or '\0' in word or '"' in word or '\\' in word:
            raise ValueError(f'unsafe lexicon spelling: {word!r}')
        flag = 1 if row[1] in LEXICAL else 2 if row[1] == 'verb' else 4
        words[word] = words.get(word, 0) | flag
        categories.setdefault(word, set()).add(row[1])
    return words, categories


def compile_classes(source: Path) -> str:
    words, _categories = word_records(source)
    # C strcmp compares the same UTF-8 byte order as this key.
    ordered = sorted(words, key=lambda word: word.encode('utf8'))
    lines = ['/* Generated by compile_fa_stress_classes.py from Lilak;',
             ' * Copyright 2015 Mostafa Sedaghat Joo, Apache-2.0.',
             ' * See reference-lilak/persian/NOTICE and LICENSE. */']
    positions, banks, offset = [], [], 0
    for word in ordered:
        size = len(word.encode('utf8')) + 1
        # Stay below the ISO C limit for a single concatenated literal,
        # including the compiler-provided final NUL.
        if not banks or offset + size >= 3500:
            banks.append([])
            offset = 0
        positions.append((len(banks) - 1, offset))
        banks[-1].append(word)
        offset += size
    for i, bank in enumerate(banks):
        lines.append(f'static const char fa_stress_bank_{i}[] =')
        lines.extend(f'    "{word}\\0"' for word in bank)
        lines[-1] += ';'
    lines.append('static const char *const fa_stress_banks[] = {')
    lines.extend(f'    fa_stress_bank_{i},' for i in range(len(banks)))
    lines.append('};')
    lines.append('static const struct fa_stress_class fa_stress_classes[] = {')
    lines.extend(f'    {{{bank}u, {offset}u, {words[word]}u}},'
                 for word, (bank, offset) in zip(ordered, positions))
    lines.extend(('};', ''))
    return '\n'.join(lines)


def compile_adjective_final_y(source: Path) -> str:
    """Flag classified adjectives separately from ambiguous noun + -i."""
    words, categories = word_records(source)
    ordered = sorted(words, key=lambda word: word.encode('utf8'))
    adjective = {'adjective', 'adjective_comparative', 'adjective_superlative'}
    allowed = adjective | {'adverb'}
    bits = bytearray((len(ordered) + 7) // 8)
    for index, word in enumerate(ordered):
        kinds = categories[word]
        if word.endswith('ی') and kinds <= allowed and kinds & adjective:
            bits[index // 8] |= 1 << (index % 8)
    lines = ['/* Generated by compile_fa_stress_classes.py from the same Lilak',
             ' * spelling/POS classes, Apache-2.0. Bits follow fa_stress_classes.',
             ' * Only adjective-only or adjective/adverb entries ending in ی. */',
             'static const unsigned char fa_stress_adjective_final_y[] = {']
    for offset in range(0, len(bits), 16):
        lines.append('    ' + ', '.join('0x%02x' % value for value in bits[offset:offset + 16]) + ',')
    lines.extend(('};', ''))
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=HERE / 'direct_fa_stress_classes.inc')
    parser.add_argument('--adjective-output', type=Path, default=HERE / 'direct_fa_adjective_final_y.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = compile_classes(args.source)
    adjectives = compile_adjective_final_y(args.source)
    if args.check:
        if args.output.read_text(encoding='utf8') != value:
            raise SystemExit('Persian stress classes need regeneration')
        if args.adjective_output.read_text(encoding='utf8') != adjectives:
            raise SystemExit('Persian adjective stress classes need regeneration')
    else:
        args.output.write_text(value, encoding='utf8', newline='\n')
        args.adjective_output.write_text(adjectives, encoding='utf8', newline='\n')
    print('Checked' if args.check else 'Generated', 'Persian stress classes.')


if __name__ == '__main__':
    main()
