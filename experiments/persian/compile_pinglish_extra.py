"""Generate unambiguous Latin forms for existing Persian symbol-name words."""
from __future__ import annotations

import argparse
from collections import defaultdict
import ctypes
import hashlib
from pathlib import Path
import re

from compile_direct_symbols import NAMES
from compile_pinglish_lexicon import latin_key
from direct_fa_vocalized_rules import EXTRA

HERE = Path(__file__).resolve().parent
MAIN = HERE / 'direct_fa_pinglish_lexicon.inc'
OUTPUT = HERE / 'direct_fa_pinglish_extra.inc'


def generate(library: Path) -> str:
    dll = ctypes.CDLL(str(library.resolve()))
    translate, release = dll.eciPersianTranslateUtf8, dll.eciPersianRelease
    translate.argtypes = (ctypes.c_char_p, ctypes.c_size_t, ctypes.POINTER(ctypes.c_void_p),
                          ctypes.POINTER(ctypes.POINTER(ctypes.c_size_t)), ctypes.POINTER(ctypes.c_size_t))
    translate.restype = ctypes.c_int
    release.argtypes = (ctypes.c_void_p,)
    existing = set(re.findall(r'^\s*\{"([a-z]+)",', MAIN.read_text(encoding='utf8'), re.M))
    candidates = set(EXTRA)
    candidates.update(part for label in NAMES.values() for part in label.split())
    groups = defaultdict(list)
    for word in sorted(candidates, key=lambda value: value.encode('utf8')):
        # A marked or joined form can have a different stress from its base.
        if any('\u064b' <= char <= '\u065f' or char == '\u200c' for char in word):
            continue
        raw = word.encode('utf8')
        out, mapping, error = ctypes.c_void_p(), ctypes.POINTER(ctypes.c_size_t)(), ctypes.c_size_t()
        if translate(raw, len(raw), ctypes.byref(out), ctypes.byref(mapping), ctypes.byref(error)):
            continue
        try:
            tag = ctypes.string_at(out).decode('ascii')
        finally:
            release(out)
            release(mapping)
        key = latin_key(tag)
        if key and key not in existing:
            groups[key].append((word, tag))
    selected = [(key, values[0][0]) for key, values in sorted(groups.items())
                if len({tag for _, tag in values}) == 1]
    sources = (HERE / 'direct_fa_vocalized_rules.py', HERE / 'compile_direct_symbols.py', MAIN)
    hashes = ' '.join(hashlib.sha256(path.read_bytes()).hexdigest() for path in sources)
    lines = ['/* Generated by compile_pinglish_extra.py from verified Persian symbol-name',
             ' * and vocalized-word bases; ambiguous Latin spellings are excluded.',
             f' * Sources SHA256: {hashes}',
             ' */',
             'static const struct fa_pinglish_entry fa_pinglish_extra[] = {']
    for key, word in selected:
        if any(char in word for char in ('"', '\\', '\n', '\r', '\0')):
            raise ValueError(f'unsafe Persian spelling: {word!r}')
        lines.append(f'    {{"{key}", "{word}"}},')
    lines.extend(('};', ''))
    print(f'Generated {len(selected)} additional unambiguous shared Persian spellings.')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--library', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = generate(args.library)
    if args.check:
        if args.output.read_text(encoding='utf8') != value:
            raise SystemExit('additional Pinglish spellings need regeneration')
    else:
        args.output.write_text(value, encoding='utf8', newline='\n')


if __name__ == '__main__':
    main()
