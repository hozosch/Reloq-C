"""Generate unambiguous Latin forms for existing Persian symbol-name words."""
from __future__ import annotations

import argparse
import ast
from collections import defaultdict
import ctypes
import hashlib
from pathlib import Path
import re

from compile_pinglish_lexicon import latin_key
from direct_fa_vocalized_rules import EXTRA

HERE = Path(__file__).resolve().parent
MAIN = HERE / 'direct_fa_pinglish_lexicon.inc'
OUTPUT = HERE / 'direct_fa_pinglish_extra.inc'


def symbol_names():
    # Read the static source table without importing the acoustic comparison
    # helpers used by its generator (which require optional NumPy).
    tree = ast.parse((HERE / 'compile_direct_symbols.py').read_text(encoding='utf8'))
    values = [node.value for node in tree.body if isinstance(node, ast.Assign) and
              any(isinstance(target, ast.Name) and target.id == 'NAMES' for target in node.targets)]
    if len(values) != 1:
        raise RuntimeError('missing or ambiguous Persian symbol-name table')
    names = ast.literal_eval(values[0])
    if not isinstance(names, dict):
        raise RuntimeError('invalid Persian symbol-name table')
    return names


def generate(library: Path) -> str:
    dll = ctypes.CDLL(str(library.resolve()))
    translate, release = dll.eciPersianTranslateUtf8, dll.eciPersianRelease
    translate.argtypes = (ctypes.c_char_p, ctypes.c_size_t, ctypes.POINTER(ctypes.c_void_p),
                          ctypes.POINTER(ctypes.POINTER(ctypes.c_size_t)), ctypes.POINTER(ctypes.c_size_t))
    translate.restype = ctypes.c_int
    release.argtypes = (ctypes.c_void_p,)
    existing = set(re.findall(r'^\s*\{"([a-z]+)",', MAIN.read_text(encoding='utf8'), re.M))
    candidates = set(EXTRA)
    candidates.update(part for label in symbol_names().values() for part in label.split())
    groups = defaultdict(list)
    for word in sorted(candidates, key=lambda value: value.encode('utf8')):
        # A marked or joined form can have a different stress from its base.
        if any('\u064b' <= char <= '\u065f' or char == '\u200c' for char in word):
            continue
        raw = word.encode('utf8')
        out, mapping, error = ctypes.c_void_p(), ctypes.POINTER(ctypes.c_size_t)(), ctypes.c_size_t()
        if translate(raw, len(raw), ctypes.byref(out), ctypes.byref(mapping), ctypes.byref(error)):
            continue
        try:
            tag = ctypes.string_at(out).decode('ascii')
        finally:
            release(out)
            release(mapping)
        key = latin_key(tag)
        if key and key not in existing:
            groups[key].append((word, tag))
    selected = [(key, values[0][0]) for key, values in sorted(groups.items())
                if len({tag for _, tag in values}) == 1]
    sources = (HERE / 'direct_fa_vocalized_rules.py', HERE / 'compile_direct_symbols.py', MAIN)
    hashes = ' '.join(hashlib.sha256(path.read_bytes()).hexdigest() for path in sources)
    lines = ['/* Generated by compile_pinglish_extra.py from verified Persian symbol-name',
             ' * and vocalized-word bases; ambiguous Latin spellings are excluded.',
             f' * Sources SHA256: {hashes}',
             ' */',
             'static const struct fa_pinglish_entry fa_pinglish_extra[] = {']
    for key, word in selected:
        if any(char in word for char in ('"', '\\', '\n', '\r', '\0')):
            raise ValueError(f'unsafe Persian spelling: {word!r}')
        lines.append(f'    {{"{key}", "{word}"}},')
    lines.extend(('};', ''))
    print(f'Generated {len(selected)} additional unambiguous shared Persian spellings.')
    return '\n'.join(lines)


def matches_without_redundant_additions(library: Path, current: str, generated: str) -> bool:
    """Accept added mappings only if the running core already says them identically.

    A new Persian word can become available without needing a Pinglish alias:
    the explicit Roman spelling may already produce the very same phones.
    Existing entries, source fingerprints and all other generated text must
    still match exactly; a genuinely missing alias still requires regeneration.
    """
    pattern = re.compile(r'^\s*\{"([a-z]+)", "([^"\\]+)"\},$', re.M)
    old = dict(pattern.findall(current))
    proposed = dict(pattern.findall(generated))
    if any(proposed.get(key) != word for key, word in old.items()):
        return False
    added = {key: word for key, word in proposed.items() if key not in old}
    if not added:
        return False
    dll = ctypes.CDLL(str(library.resolve()))
    pinglish = dll.eciPersianPinglishWord
    pinglish.argtypes = (ctypes.c_char_p, ctypes.c_size_t, ctypes.c_void_p, ctypes.c_size_t)
    pinglish.restype = ctypes.c_int
    translate, release = dll.eciPersianTranslateUtf8, dll.eciPersianRelease
    translate.argtypes = (ctypes.c_char_p, ctypes.c_size_t, ctypes.POINTER(ctypes.c_void_p),
                          ctypes.POINTER(ctypes.POINTER(ctypes.c_size_t)), ctypes.POINTER(ctypes.c_size_t))
    translate.restype = ctypes.c_int
    release.argtypes = (ctypes.c_void_p,)
    for key, word in added.items():
        raw = key.encode('ascii'); actual = ctypes.create_string_buffer(2048)
        if pinglish(raw, len(raw), actual, len(actual)) != 1:
            return False
        raw = word.encode('utf8'); expected = ctypes.c_void_p()
        mapping, error = ctypes.POINTER(ctypes.c_size_t)(), ctypes.c_size_t()
        if translate(raw, len(raw), ctypes.byref(expected), ctypes.byref(mapping), ctypes.byref(error)):
            return False
        try:
            if actual.value != ctypes.string_at(expected):
                return False
        finally:
            release(expected);release(mapping)
    filtered = '\n'.join(line for line in generated.split('\n')
                         if not ((match := pattern.fullmatch(line)) and match.group(1) in added))
    return filtered == current


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--library', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = generate(args.library)
    if args.check:
        current = args.output.read_text(encoding='utf8')
        if current != value and not matches_without_redundant_additions(args.library, current, value):
            raise SystemExit('additional Pinglish spellings need regeneration')
    else:
        args.output.write_text(value, encoding='utf8', newline='\n')


if __name__ == '__main__':
    main()
