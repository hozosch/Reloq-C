"""Generate conservative Pinglish spellings from the native Persian lexicon.

Candidates come from the existing Persian word and grammatical-class tables.
Only a Roman spelling with one unambiguous native pronunciation survives;
unresolved collisions continue to the existing Pinglish rules. The generated
table stores Persian spellings, so runtime pronunciation and stress still
come from the shared Persian implementation rather than a copied snapshot.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import ctypes
import hashlib
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
LEXICON = HERE / 'direct_fa_lexicon.inc'
CLASSES = HERE / 'direct_fa_stress_classes.inc'
ALIASES = HERE / 'direct_fa_pinglish_aliases.inc'
OUTPUT = HERE / 'direct_fa_pinglish_lexicon.inc'


def latin_key(tag: str) -> str | None:
    if not re.fullmatch(r'`\[(?:\.[012][^].]+)+\]', tag):
        return None
    phones = re.sub(r'\.[012]', '', tag[2:-1]).replace("'", '').replace(':', '')
    if phones.endswith('hw'):
        phones = phones[:-1]  # Native final-H marker is not a second sound.
    # Adjacent vowels must survive the writer's greedy aa convention. For
    # example two front vowels cannot be indexed under aa, which denotes one
    # back vowel; an ambiguous sequence stays with the explicit input rules.
    for run in re.findall(r'[Aa]+', phones):
        encoded = ''.join('a' if phone == 'A' else 'aa' for phone in run)
        decoded, at = [], 0
        while at < len(encoded):
            back = encoded[at:at + 2] == 'aa'
            decoded.append('a' if back else 'A')
            at += 2 if back else 1
        if ''.join(decoded) != run:
            return None
    mapping = {'G': 'kh', 'R': 'gh', 'S': 'sh', 'Z': 'zh', 'C': 'ch',
               'J': 'j', 'j': 'y', 'A': 'a', 'a': 'aa'}
    result = []
    for phone in phones:
        if phone in mapping:
            result.append(mapping[phone])
        elif phone in 'abcdefghijklmnopqrstuvwxyz':
            result.append(phone)
        else:
            return None
    raw = ''.join(result)
    # Match the runtime lookup normalization before grouping collisions.
    # Keep a versus aa distinct: collapsing them would let a lookup change
    # the vowel quality explicitly specified by a Pinglish writer.
    normalized, i = [], 0
    while i < len(raw):
        pair = raw[i:i + 2]
        if pair in ('ee', 'oo', 'ou', 'jh'):
            normalized.append({'ee': 'i', 'oo': 'u', 'ou': 'u', 'jh': 'zh'}[pair])
            i += 2
        else:
            normalized.append(raw[i])
            i += 1
    key = ''.join(normalized)
    return key if 3 <= len(key) <= 128 else None


def compile_table(library: Path) -> str:
    dll = ctypes.CDLL(str(library.resolve()))
    translate, release = dll.eciPersianTranslateUtf8, dll.eciPersianRelease
    translate.argtypes = (ctypes.c_char_p, ctypes.c_size_t, ctypes.POINTER(ctypes.c_void_p),
                          ctypes.POINTER(ctypes.POINTER(ctypes.c_size_t)), ctypes.POINTER(ctypes.c_size_t))
    translate.restype = ctypes.c_int
    release.argtypes = (ctypes.c_void_p,)

    def pronunciation(word: str) -> str | None:
        value = word.encode('utf8')
        out, mapping, error = ctypes.c_void_p(), ctypes.POINTER(ctypes.c_size_t)(), ctypes.c_size_t()
        if translate(value, len(value), ctypes.byref(out), ctypes.byref(mapping), ctypes.byref(error)):
            return None
        try:
            return ctypes.string_at(out).decode('ascii')
        finally:
            release(out)
            release(mapping)

    lexicon = LEXICON.read_text(encoding='utf8')
    classes = CLASSES.read_text(encoding='utf8')
    words = set(re.findall(r'^\s*\{"([^"\\]+)",\s*"`\[', lexicon, re.M))
    words.update(re.findall(r'^\s+"(.*?)\\0"', classes, re.M))
    groups = defaultdict(list)
    for word in sorted(words, key=lambda value: value.encode('utf8')):
        tag = pronunciation(word)
        key = latin_key(tag) if tag else None
        if key:
            groups[key].append((word, tag))
    # Explicitly recognized spellings also serve the phrase parser. Never
    # generate a conflicting entry that the word parser could not reach.
    aliases = dict(re.findall(r'\{"([a-z]+)","([^"\\]+)"\}',
                              ALIASES.read_text(encoding='utf8')))
    selected = [(key, values[0][0]) for key, values in sorted(groups.items())
                if len({tag for _word, tag in values}) == 1 and
                (key not in aliases or pronunciation(aliases[key]) == values[0][1])]
    metadata = (f'lexicon={hashlib.sha256(LEXICON.read_bytes()).hexdigest()}, '
                f'classes={hashlib.sha256(CLASSES.read_bytes()).hexdigest()}, '
                f'aliases={hashlib.sha256(ALIASES.read_bytes()).hexdigest()}')
    lines = ['/* Generated by compile_pinglish_lexicon.py; do not edit.',
             ' * Sources: the Persian eSpeak-derived word table (GPL-3.0+) and',
             ' * Lilak grammatical classes (Apache-2.0); see their NOTICE files.',
             ' * Only one-pronunciation Roman spellings are admitted.',
             f' * {metadata}', ' */',
             'static const struct fa_pinglish_entry fa_pinglish_entries[] = {']
    for key, word in selected:
        if any(char in word for char in ('"', '\\', '\n', '\r', '\0')):
            raise ValueError(f'unsafe Persian spelling: {word!r}')
        lines.append(f'    {{"{key}", "{word}"}},')
    lines.extend(('};', ''))
    print(f'{len(selected)} unambiguous Pinglish spellings; '
          f'{len(groups)-len(selected)} ambiguous spellings left to the existing rules.')
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--library', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    table = compile_table(args.library)
    if args.check:
        if args.output.read_text(encoding='utf8') != table:
            raise SystemExit('Pinglish lexicon needs regeneration')
    else:
        args.output.write_text(table, encoding='utf8', newline='\n')


if __name__ == '__main__':
    main()
