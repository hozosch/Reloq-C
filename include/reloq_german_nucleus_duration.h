#ifndef RELOQ_GERMAN_NUCLEUS_DURATION_H
#define RELOQ_GERMAN_NUCLEUS_DURATION_H

#include "reloq_german_phone_sequence.h"
/* Observed e/i/o/u shortening in an open unstressed polysyllabic syllable.
 * Rounded front vowels need their lexical quantity class (e.g. ueberall). */
int reloq_german_nucleus_shortened(const struct reloq_german_phone_node *node);
#include <stddef.h>
#include <stdint.h>

/* A linguistic nucleus, before phrase prominence and boundary lengthening.
 * The closing phone is NONE, postvocalic r, l, or a diphthong glide j/w.
 * For a diphthong followed by l use the public quoted diphthong as head.
 * third is NONE or l following a closing glide. shortened is the reduced
 * quantity of a closed or nasal vowel, separate from syllable stress. */
struct reloq_german_nucleus_duration {
    int32_t base_ticks;
    int32_t closing_ticks;
    int32_t glide_ticks; /* fixed part before closing l in a triphone */
};

/* Return 1 for a described nucleus, 0 for an unsupported combination and
 * -1 for invalid arguments. Failure leaves out unchanged. No spelling,
 * reference ABI, executable tables, or original functions enter this API. */
int reloq_german_nucleus_duration_base(enum reloq_german_phone head,
    enum reloq_german_phone closing, enum reloq_german_phone third, int shortened,
    struct reloq_german_nucleus_duration *out);

/* Locate the acoustic nucleus within one already syllabified phone group.
 * A standalone R is a vowel; postvocalic r/j/w and then l join its nucleus.
 * Quoted diphthongs are one public token even though acoustically bipartite.
 * Returns 1 with offsets, 0 when no vowel nucleus exists, -1 on bad input.
 * Unmodified output on 0/-1. This does not perform word/morpheme analysis. */
int reloq_german_nucleus_find(const struct reloq_german_phone_node *phones,
    size_t count, size_t *first, size_t *length);

/* The fixed intervals surround one free vowel portion. Values have already
 * been generated by transition/closing-phone rules. minimum is the acoustic
 * minimum for that particular interval, typically one or three ticks. */
struct reloq_nucleus_interval { int32_t ticks, minimum; };

/* Distribute an already phrase/rate-adjusted budget. A shortage compresses
 * every fixed interval twice, reserving the free portion between passes.
 * Each pass rounds each interval separately; final minima can exceed the
 * requested budget. Returns 0, or -1 without changing output on invalid
 * input. Input and output arrays must not overlap. No allocation is needed.
 * Counts and totals must fit signed 16 bits.
 * This stage deliberately does not estimate the phrase-adjusted budget. */
int reloq_german_nucleus_distribute(
    const struct reloq_nucleus_interval *fixed, size_t count,
    double requested_ticks, int32_t vowel_minimum,
    int32_t *fixed_out, int32_t *vowel_out);

#endif
