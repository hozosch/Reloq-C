"""Compile complete SAPI dialog translations into a small read-only C table."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANGS = {'en': 0x09, 'de': 0x07, 'es': 0x0a, 'fr': 0x0c, 'it': 0x10,
         'pt': 0x16, 'fi': 0x0b, 'el': 0x08, 'ja': 0x11, 'ko': 0x12,
         'zh': 0x04, 'zh-Hant': 0x404}


def generate():
    data = json.loads((HERE / 'ui.json').read_text())
    keys = data.pop('keys')
    assert set(data) == set(LANGS)
    assert len(set(keys)) == len(keys)
    out = ['/* Generated by generate_ui.py; no runtime translation dependency. */',
           'enum sapi_ui_text {' + ','.join('UI_' + k for k in keys) + ',UI_COUNT};',
           'struct sapi_ui { unsigned language; const WCHAR *text[UI_COUNT]; };',
           'static const struct sapi_ui sapi_ui_languages[]={']
    for lang, values in data.items():
        assert len(values) == len(keys), (lang, len(values), len(keys))
        assert all(isinstance(v, str) and v for v in values)
        out.append('    {0x%x,{%s}},' % (LANGS[lang], ','.join('L' + json.dumps(v, ensure_ascii=False) for v in values)))
    return '\n'.join(out + ['};', '''static const struct sapi_ui *sapi_ui_for_language(unsigned language)
{
    unsigned primary=language&0x3ff,sub=language>>10;
    if(primary==4&&(sub==1||sub==3||sub==5))return sapi_ui_languages+11;
    for(unsigned i=0;i<sizeof sapi_ui_languages/sizeof *sapi_ui_languages;++i)
        if(sapi_ui_languages[i].language==primary)return sapi_ui_languages+i;
    return sapi_ui_languages;
}''', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        assert (HERE / 'ui.inc').read_text() == content, 'SAPI translations are stale'
    else:
        (HERE / 'ui.inc').write_text(content)
