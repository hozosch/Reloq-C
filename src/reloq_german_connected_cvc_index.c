static int compare(const unsigned char *a, size_t alen,
                   const unsigned char *b, size_t blen)
{
    size_t common = alen < blen ? alen : blen;
    int order = memcmp(a, b, common);
    return order ? order : (alen > blen) - (alen < blen);
}

static const struct positive_context *lookup(const unsigned char *word,
                                              size_t length)
{
    size_t lo = 0, hi = sizeof entries / sizeof entries[0];
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        int order = compare(word, length, entries[mid].word,
                            entries[mid].length);
        if (order == 0) return &entries[mid];
        if (order > 0) lo = mid + 1;
        else hi = mid;
    }
    return NULL;
}

int reloq_german_connected_cvc_reference_pair(
    const unsigned char *left, size_t left_length,
    const unsigned char *right, size_t right_length)
{
    if (!left || !right || !left_length || !right_length) return -1;
    static const char *carriers[] = {"Pack", "Hut", "App"};
    const struct positive_context *first = lookup(left, left_length);
    const struct positive_context *second = lookup(right, right_length);
    for (size_t j = 0; j < sizeof carriers / sizeof carriers[0]; ++j) {
        size_t n = strlen(carriers[j]);
        if (first && right_length == n &&
            memcmp(right, carriers[j], n) == 0 &&
            (first->mask & (1u << j))) return 1;
        if (second && left_length == n &&
            memcmp(left, carriers[j], n) == 0 &&
            (second->mask & (1u << (3 + j)))) return 1;
    }
    for (size_t i = 0; i < sizeof pair_entries / sizeof pair_entries[0]; ++i)
        if (compare(left, left_length, pair_entries[i].left,
                    pair_entries[i].left_length) == 0 &&
            compare(right, right_length, pair_entries[i].right,
                    pair_entries[i].right_length) == 0) return 1;
    return 0;
}
