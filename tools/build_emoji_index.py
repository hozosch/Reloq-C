"""Index Unicode 17 RGI emoji against the existing CLDR 48 name pools.

Only offsets and property ranges are emitted, never a second set of names.
Ordinary builds use the checked-in C data and need neither Python nor a
Unicode library. Supply the official Unicode 17 emoji-test.txt and
ucd/emoji/emoji-data.txt to regenerate it. Their SHA-256 hashes are recorded
in the generated header.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(test, properties):
    names = (ROOT / "src/reloq_unicode_data.inc").read_text()
    array = names.split("static const unsigned char unicode_strings[] = {", 1)[1].split("};", 1)[0]
    pool = bytes(map(int, re.findall(r"\d+", array)))
    table = names.split("unicode_cldr[] = {", 1)[1].split("};", 1)[0]
    offsets = {}
    for key, de, en in re.findall(r"\{(\d+),(\d+),(\d+)\}", table):
        key = int(key)
        offsets[pool[key:pool.index(0, key)].decode()] = key
    keys = set()
    for line in test.read_text().splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        points, status = map(str.strip, data.split(";"))
        if status == "fully-qualified":
            keys.add("".join(chr(int(cp, 16)) for cp in points.split() if cp != "FE0F"))
    missing = sorted(keys - offsets.keys())
    if missing:
        raise ValueError(f"CLDR pool lacks {len(missing)} emoji names: {missing[:8]}")
    ranges = []
    for line in properties.read_text().splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        points, prop = map(str.strip, data.split(";"))
        if prop != "Emoji_Presentation":
            continue
        points = points.split("..")
        start, end = int(points[0], 16), int(points[-1], 16)
        if ranges and start == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], end)
        else:
            ranges.append((start, end))
    result = ["/* Unicode 17 / CLDR 48; Unicode License V3.",
              " * Offsets reuse existing localized names. Generated by tools/build_emoji_index.py."]
    for path in (test, properties):
        result.append(f" * {path.name} SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}")
    result += [" */", "static const uint32_t unicode_emoji_keys[] = {"]
    ordered = sorted(keys, key=lambda key: key.encode())
    for i in range(0, len(ordered), 12):
        result.append(",".join(str(offsets[key]) for key in ordered[i:i + 12]) + ",")
    result += ["};", "static const struct unicode_emoji_range { uint32_t first, last; } unicode_emoji_presentation[] = {"]
    result.extend(f"{{0x{start:x},0x{end:x}}}," for start, end in ranges)
    result += ["};", ""]
    return "\n".join(result), len(keys), len(ranges)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("emoji_test", type=Path)
    parser.add_argument("emoji_data", type=Path)
    args = parser.parse_args()
    text, count, ranges = generate(args.emoji_test, args.emoji_data)
    (ROOT / "src/reloq_unicode_emoji.inc").write_text(text)
    print(f"Emoji index: {count} sequences, {ranges} default-presentation ranges; no duplicated names")
