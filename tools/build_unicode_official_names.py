"""Generate canonical Unicode 18 names for Persian character fallback."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference-unicode/persian/derived-names-delta18.txt'
OUTPUT = ROOT / 'src/reloq_unicode_official.inc'
PY_SOURCE = ROOT / 'reference-unicode/persian/python-names-delta15to18.txt'
PY_OUTPUT = ROOT / 'experiments/persian/persian_unicode_names.py'


def generate() -> str:
    entries, ranges = [], []
    for line in SOURCE.read_text(encoding='ascii').splitlines():
        if not line or line.startswith('#'):
            continue
        code, name = line.split(';', 1)
        if '..' in code:
            first, last = (int(value, 16) for value in code.split('..'))
            if not name.endswith('-*'):
                raise ValueError('unexpected algorithmic Unicode name')
            ranges.append((first, last, name[:-2].lower()))
        else:
            entries.append((int(code, 16), name.lower()))
    if entries != sorted(entries) or ranges != sorted(ranges):
        raise ValueError('Unicode name tables must be sorted')
    lines = ['/* Canonical Unicode 18.0 names; Unicode License V3.',
             ' * Generated by tools/build_unicode_official_names.py. */',
             'static const struct { uint32_t cp; const char *name; } unicode_official_names[] = {']
    lines.extend('    {0x%xu, %s},' % (cp, json.dumps(name)) for cp, name in entries)
    lines.extend(('};', 'static const struct { uint32_t first, last; const char *prefix; } unicode_official_ranges[] = {'))
    lines.extend('    {0x%xu, 0x%xu, %s},' % (first, last, json.dumps(prefix))
                 for first, last, prefix in ranges)
    return '\n'.join((*lines, '};', ''))


def generate_python() -> str:
    entries, ranges = {}, []
    for line in PY_SOURCE.read_text(encoding='ascii').splitlines():
        if not line or line.startswith('#'):
            continue
        code, name = line.split(';', 1)
        if '..' in code:
            first, last = (int(value, 16) for value in code.split('..'))
            if not name.endswith('-*'):
                raise ValueError('unexpected algorithmic Unicode name')
            ranges.append((first, last, name[:-2].lower()))
        else:
            entries[int(code, 16)] = ' '.join(name.lower().replace('-', ' ').split())
    return ('"""Generated Unicode 18 additions; Unicode License V3.\n\n'
            'Regenerate with tools/build_unicode_official_names.py.\n"""\n'
            'from __future__ import annotations\n\nimport unicodedata\n\n'
            '_NAMES = ' + pprint.pformat(entries, width=110, sort_dicts=False) + '\n'
            '_RANGES = ' + pprint.pformat(tuple(ranges), width=110) + '\n\n'
            'def official_name(char: str) -> str:\n'
            '    code = ord(char)\n'
            '    for first, last, prefix in _RANGES:\n'
            '        if first <= code <= last:\n'
            '            return f"{prefix} {code:x}"\n'
            '    return _NAMES.get(code, " ".join(unicodedata.name(char, "").lower().replace("-", " ").split()))\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value, py_value = generate(), generate_python()
    if args.check:
        if OUTPUT.read_text(encoding='ascii') != value or PY_OUTPUT.read_text(encoding='ascii') != py_value:
            raise SystemExit('official Unicode names need regeneration')
    else:
        OUTPUT.write_text(value, encoding='ascii', newline='\n')
        PY_OUTPUT.write_text(py_value, encoding='ascii', newline='\n')
    print(f'{"Checked" if args.check else "Generated"} canonical Unicode names and ranges.')


if __name__ == '__main__':
    main()
