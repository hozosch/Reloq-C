#!/usr/bin/env python3
"""Generate immutable native word-segmentation and Unicode case tables.

The English lists retain the OpenEVV attribution in nvda/wordseg-data/NOTICE.
Run this after updating those source lists; no runtime files are required.
"""
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "nvda" / "wordseg-data"
OUTPUT = ROOT / "src" / "reloq_wordseg_data.inc"


def pieces(language):
    values, abbreviations, section = set(), set(), False
    for line in (DATA / (language + "-pieces")).read_text(encoding="utf8").splitlines():
        if line.startswith("# Abbreviations said by their letters"):
            section = True
        elif line.startswith("# Prefixes"):
            section = False
        elif line.strip() and not line.startswith("#"):
            value = line.strip()
            values.add(value)
            if section:
                abbreviations.add(value)
    return values, abbreviations


def emit_group(output, name, words):
    words = sorted(words)
    output.append(f"static const char *const {name}[] = {{\n")
    for word in words:
        if not word.isascii() or not word.isalpha():
            raise ValueError((name, word))
        output.append(f'    "{word}",\n')
    output.append("};\n")


def emit_known_words(output, words):
    """Exact, prefix-bucketed words without one native pointer per word."""
    groups = {}
    for word in sorted(words):
        if 2 <= len(word) <= 32:
            groups.setdefault(word[:2], []).append(word[2:])
    starts, chunks = [], []
    for first in 'abcdefghijklmnopqrstuvwxyz':
        for second in 'abcdefghijklmnopqrstuvwxyz':
            starts.append(len(chunks))
            values = groups.get(first + second, [])
            chunks.extend(values[i:i + 64] for i in range(0, len(values), 64))
    starts.append(len(chunks))
    if len(chunks) >= 65536:
        raise ValueError('too many English vocabulary chunks')
    output.append('static const uint16_t wordseg_known_start[] = {\n')
    for i in range(0, len(starts), 16):
        output.append('    ' + ','.join(map(str, starts[i:i + 16])) + ',\n')
    output.append('};\nstatic const struct wordseg_known_chunk wordseg_known_chunks[] = {\n')
    for chunk in chunks:
        output.append('    {"' + ''.join(word + r'\0' for word in chunk) + '",' + str(len(chunk)) + '},\n')
    output.append('};\n')


def case_flags(ch):
    upper = ch.isupper() or (ch.isalpha() and ch.istitle())
    lower = ch.islower()
    mark = unicodedata.category(ch).startswith("M")
    word = ch.isalnum() or mark or ch in "_'’"
    return int(lower) | int(upper) * 2 | int(mark) * 4 | int(word) * 8


def main():
    out = ["/* Generated by tools/generate_wordseg_data.py; do not edit. */\n"]
    us, abbr = pieces("enus")
    gb, gb_abbr = pieces("engb")
    if us != gb or abbr != gb_abbr:
        raise ValueError("English piece tables differ; represent them separately")
    emit_group(out, "wordseg_pieces", us)
    emit_group(out, "wordseg_abbreviations", abbr)
    # Protect ordinary words with an established pronunciation in the
    # project's independently observed English vocabularies. The native
    # engine remains responsible for saying them in each dialect. In
    # particular, a spelling that happens to consist of two known pieces
    # does not imply that the word is pronounced as those pieces.
    observed = set()
    for name in ("reloq_english_lexicon.inc", "reloq_english_vocabulary82.inc",
                 "reloq_english_vocabulary83.inc"):
        source = (ROOT / "src" / name).read_text(encoding="utf8")
        observed.update(re.findall(r'^\s*\{"([a-z]+)"\s*,', source, re.M))
    if len(observed) < 50000:
        raise ValueError("observed English vocabulary is incomplete")
    emit_known_words(out, observed - us)
    for language in ("enus", "engb"):
        groups = {"onset": set(), "coda": set(), "word": set()}
        for line in (DATA / (language + "-sayable")).read_text(encoding="utf8").splitlines():
            if line and not line.startswith("#"):
                kind, value = line.split(maxsplit=1)
                groups[kind].add(value)
        for kind, words in groups.items():
            emit_group(out, f"wordseg_{language}_{kind}", words)
    ranges, start, previous = [], None, 0
    for code in range(0x110000):
        flags = case_flags(chr(code))
        if flags != previous:
            if previous:
                ranges.append((start, code - 1, previous))
            start, previous = code if flags else None, flags
    if previous:
        ranges.append((start, 0x10ffff, previous))
    out.append("static const struct wordseg_category_range wordseg_categories[] = {\n")
    for start, end, flags in ranges:
        out.append(f"    {{0x{start:x},0x{end:x},{flags}}},\n")
    out.append("};\n")
    out.append("static const struct wordseg_casefold_entry wordseg_casefolds[] = {\n")
    for code in range(0x110000):
        ch = chr(code)
        folded = ch.casefold()
        if folded != ch:
            encoded = "".join(f"\\x{byte:02x}" for byte in folded.encode("utf8"))
            out.append(f'    {{0x{code:x},"{encoded}"}},\n')
    out.append("};\n")
    OUTPUT.write_text("".join(out), encoding="ascii")


if __name__ == "__main__":
    main()
