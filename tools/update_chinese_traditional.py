"""Generate compact pronunciation identities for ambiguous Han simplifications.

Unicode's many-to-one traditional families distinguish meanings, unlike
one-to-one regional spelling/pronunciation differences. Native word readings
remain authoritative when compatible with the original character identity.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import unicodedata

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/"data/chinese_traditional_readings.json"
OUTPUT=ROOT/"vendor/openevv61/rom/cjk/reloq_chinese_traditional.inc"


def pinyin(value):
    result="";tone=0
    for c in unicodedata.normalize("NFD",value):
        if c in "\u0304\u0301\u030c\u0300":tone={"\u0304":1,"\u0301":2,"\u030c":3,"\u0300":4}[c]
        elif c=="\u0308":result+="u"  # native ü spelling: nuu, luue, ...
        elif c=="\u0302":continue
        else:result+=c
    assert result.isascii() and result.isalpha(),value
    return result+str(tone)


def snapshot(directory):
    fields={};sources={}
    for name in ("Unihan_Readings.txt","Unihan_Variants.txt"):
        raw=(directory/name).read_bytes();sources[name]=hashlib.sha256(raw).hexdigest()
        assert "Unicode Version 17.0.0" in raw[:1000].decode()
        for line in raw.decode().splitlines():
            if not line.startswith("U+"):continue
            scalar,key,value=line.split("\t")
            if key in ("kMandarin","kHanyuPinyin","kTraditionalVariant"):
                fields.setdefault(int(scalar[2:],16),{})[key]=value
    families=[]
    for cp,row in sorted(fields.items()):
        variants=[int(x,16) for x in re.findall(r"U\+([A-F0-9]+)",row.get("kTraditionalVariant",""))]
        if len(variants)<2:continue
        families.append(dict(simplified=cp,traditional=[dict(scalar=v,
            mandarin=fields.get(v,{}).get("kMandarin",""),
            hanyu_pinyin=fields.get(v,{}).get("kHanyuPinyin","")) for v in variants]))
    return dict(unicode_version="17.0.0",source="https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip",
                license="Unicode-3.0",source_sha256=sources,families=families)


def generate(data):
    text=(ROOT/"vendor/openevv61/rom/cjk/reloq_cjk_data.inc").read_text()
    block=text.split("chinese_variants[]={",1)[1].split("};",1)[0]
    forms=dict(tuple(map(int,r)) for r in re.findall(r"\{(\d+),(\d+)\}",block))
    rows={}
    for family in data["families"]:
        options={row["scalar"]:list(dict.fromkeys(pinyin(s) for s in row["mandarin"].split())) for row in family["traditional"]}
        if len({r for readings in options.values() for r in readings})<2:continue
        for cp,readings in options.items():
            if readings and cp!=family["simplified"] and forms.get(cp,cp)==family["simplified"]:
                # Contextual polyphony must survive: 殼 can be qiào in
                # 甲殼 even though its standalone Mandarin entry is ké.
                entry=next(row for row in family["traditional"] if row["scalar"]==cp)
                alternatives=[pinyin(p) for block in entry.get("hanyu_pinyin","").split()
                    for p in block.split(":",1)[-1].split(",")]
                rows[cp]=" ".join(dict.fromkeys(readings+alternatives))
    output="/* Unicode 17.0 Unihan: distinct readings in many-to-one Han families.\n * Generated by tools/update_chinese_traditional.py; Unicode-3.0 license. */\n"
    output+="static const struct traditional_reading {uint32_t scalar;const char *readings;} traditional_readings[]={\n"
    output+="".join(f'{{{cp},"{reading}"}},\n' for cp,reading in sorted(rows.items()))+"};\n"
    return output,len(rows)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--unihan-dir",type=Path,help="refresh the frozen data subset from Unicode 17.0 Unihan files")
    p.add_argument("--check",action="store_true")
    a=p.parse_args()
    if a.unihan_dir:
        assert not a.check,"check and refresh are separate operations"
        DATA.write_text(json.dumps(snapshot(a.unihan_dir),ensure_ascii=False,indent=2)+"\n")
    result,count=generate(json.loads(DATA.read_text()))
    if a.check:assert OUTPUT.read_text()==result,"Traditional pronunciation projection needs regeneration"
    else:OUTPUT.write_text(result)
    print(f"Traditional Chinese pronunciation identities: {count} entries")


if __name__=="__main__":main()
